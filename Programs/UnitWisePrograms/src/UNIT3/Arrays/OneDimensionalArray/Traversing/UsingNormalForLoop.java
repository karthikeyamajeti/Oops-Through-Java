package UNIT3.Arrays.OneDimensionalArray.Traversing;
//WAP in Java to print the elements of a one-dimensional array using normal for loop.
public class UsingNormalForLoop {

    public static void main(String arg[]) {

        //Declaring and initializing a one-dimensional array
        int a[] = {1, 2, 3, 4, 5};

        //Using normal for loop to print array elements
        for(int i=0; i<a.length; i++){
            System.out.println(a[i]);
        }

    }
}