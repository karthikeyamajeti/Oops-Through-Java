package UNIT1.Costants;
//WAP in Java to demonstrate the use of symbolic constants.

public class SymbolicConstants {
    public static void main(String[] args) {
	//Declaring symbolic constants using the final keyword
	final double PI = 3.14159;
	final int DAYS = 7;
        
	//Displaying the values of symbolic constants
	System.out.println("PI = " + PI);
	System.out.println("Days in a Week = " + DAYS);
	System.out.println("PI = " + PI);
    }
}