package UNIT1.Costants;
//WAP in Java to demonstrate different types of literals in Java.

public class LiteralConstants {
    public static void main(String[] args) {
        
	//Declaring variables using different types of literals
	int num = 100;              //Integer Literal
	float price = 99.5f;        //Floating-Point Literal
	char grade = 'A';           //Character Literal
	String name = "Java";       //String Literal
	boolean result = true;      //Boolean Literal
	String value = null;        //Null Literal

	//Displaying the values of different literals
	System.out.println("Integer : " + num);
	System.out.println("Float   : " + price);
	System.out.println("Char    : " + grade);
	System.out.println("String  : " + name);
	System.out.println("Boolean : " + result);
	System.out.println("Null    : " + value);
        
    }
}