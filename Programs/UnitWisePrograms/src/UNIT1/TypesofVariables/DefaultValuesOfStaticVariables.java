package UNIT1.TypesofVariables;
//WAP in Java to demonstrate the default values of static variables.

public class DefaultValuesOfStaticVariables{
    //Declaring static variables of different data types
    static byte b;
    static short s;
    static int i;
    static long l;
    static float f;
    static double d;
    static char c;
    static boolean bool;
    public static void main(String[] args) {
	//Displaying the default values of static variables
        System.out.println("Byte Value: " + b);
	System.out.println("Short Value: " + s);
	System.out.println("Int Value: " + i);
	System.out.println("Long Value: " + l);
	System.out.println("Float Value: " + f);
	System.out.println("Double Value: " + d);
	System.out.println("Char Value: " + c);
	System.out.println("Boolean Value: " + bool);
    }
}