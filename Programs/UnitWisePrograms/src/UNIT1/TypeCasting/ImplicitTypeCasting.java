package UNIT1.TypeCasting;
//WAP in Java to demonstrate implicit (automatic) type casting.

public class ImplicitTypeCasting {

    public static void main(String args[]) {

        //Declaring and initializing an integer variable
        int x = 100;

        //Converting int into double automatically
        double y = x;

        //Displaying the original and converted values
        System.out.println("Integer Value = " + x);
        System.out.println("Double Value  = " + y);

    }
}